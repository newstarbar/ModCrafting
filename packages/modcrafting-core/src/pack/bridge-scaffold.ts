/**
 * A Fabric bridge project, generated as real source rather than a snippet.
 *
 * A bridge exists because two mods do not know about each other: one publishes
 * events or content, the other expects a different shape. The generated project
 * gives that seam a name (`BridgeAdapter`), wires it to the server lifecycle, and
 * leaves two explicit TODO regions where the actual API calls go. It compiles as
 * delivered and never edits a third-party jar; if a source mod has to be changed,
 * that is the transform pipeline's job, not the bridge's.
 *
 * Fabric only: the pack layer can export Forge/NeoForge packs, but authoring a
 * bridge against their APIs is a separate Java dialect this release does not
 * pretend to support.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { z } from 'zod'
import { materializeProject } from '../node.ts'
import { parseTargetId, resolveTarget } from '../version/targets.ts'
import { javaPackageFor } from './java-package.ts'
import { loadPackWorkspace } from './pack-workspace.ts'

const MOD_ID_RE = /^[a-z][a-z0-9_-]{1,63}$/

export const bridgeScaffoldRequestSchema = z.object({
  /** Pack root: supplies the loader/Minecraft target and the `mods/` directory to keep away from. */
  workspacePath: z.string().min(1),
  /** New project directory. Must not exist, or must be empty. */
  projectPath: z.string().min(1),
  modId: z.string().regex(MOD_ID_RE, 'modId 必须是小写字母开头，只含 a-z0-9_-'),
  modName: z.string().trim().min(1).max(80),
  sourceModId: z.string().regex(MOD_ID_RE, 'sourceModId 必须是小写字母开头，只含 a-z0-9_-'),
  sourceModName: z.string().trim().min(1).max(80).optional(),
  targetModId: z.string().regex(MOD_ID_RE, 'targetModId 必须是小写字母开头，只含 a-z0-9_-'),
  targetModName: z.string().trim().min(1).max(80).optional()
}).strict().refine((value) => value.sourceModId !== value.targetModId, {
  message: '桥接的两端必须是两个不同的模组', path: ['targetModId']
})
export type BridgeScaffoldRequest = z.infer<typeof bridgeScaffoldRequestSchema>

function fail(code: string, message: string): never {
  throw Object.assign(new Error(message), { code })
}

function isInside(parent: string, child: string): boolean {
  const relative = path.relative(path.resolve(parent), path.resolve(child))
  return relative === '' || (!relative.startsWith('..') && !path.isAbsolute(relative))
}

function ensureEmpty(projectPath: string): void {
  if (!existsSync(projectPath)) return
  if (!statSync(projectPath).isDirectory() || readdirSync(projectPath).length > 0) {
    fail('BRIDGE_PATH_NOT_EMPTY', `${projectPath} 已经存在且不是空目录。桥接工程只会写入新目录，避免覆盖已有代码；请换一个路径或先手动清空。`)
  }
}

function mainSource(input: {
  packageName: string
  modId: string
  sourceModId: string
  targetModId: string
}): string {
  return `package ${input.packageName};

import net.fabricmc.api.ModInitializer;
import net.fabricmc.fabric.api.command.v2.CommandRegistrationCallback;
import net.fabricmc.fabric.api.event.lifecycle.v1.ServerLifecycleEvents;
import net.fabricmc.loader.api.FabricLoader;
import net.minecraft.server.MinecraftServer;
import net.minecraft.text.Text;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import static net.minecraft.server.command.CommandManager.literal;

/**
 * Generated by ModCrafting.
 *
 * Load order is deliberately forgiving: the bridge starts even when only one of
 * the two mods is installed, reports itself as idle, and becomes active once both
 * are present. The adapter is where the two APIs meet.
 */
public final class BridgeMod implements ModInitializer {
    public static final String MOD_ID = "${input.modId}";
    public static final String SOURCE_MOD_ID = "${input.sourceModId}";
    public static final String TARGET_MOD_ID = "${input.targetModId}";
    public static final Logger LOGGER = LoggerFactory.getLogger(MOD_ID);

    private static final BridgeAdapter ADAPTER = new ExampleBridgeAdapter();

    @Override
    public void onInitialize() {
        ADAPTER.onRegister();
        ServerLifecycleEvents.SERVER_STARTING.register(BridgeMod::onServerStarting);
        CommandRegistrationCallback.EVENT.register((dispatcher, registryAccess, environment) ->
            dispatcher.register(literal("${input.modId}-status")
                .requires(source -> source.hasPermissionLevel(2))
                .executes(context -> {
                    context.getSource().sendFeedback(() -> Text.literal(status()), false);
                    return 1;
                })));
        LOGGER.info("[{}] bridge loaded; expected peers: {} + {}", MOD_ID, SOURCE_MOD_ID, TARGET_MOD_ID);
    }

    private static void onServerStarting(MinecraftServer server) {
        if (!bothModsLoaded()) {
            LOGGER.warn("[{}] bridge idle: install both {} and {} to activate it", MOD_ID, SOURCE_MOD_ID, TARGET_MOD_ID);
            return;
        }
        ADAPTER.onServerStarting(server);
    }

    public static boolean bothModsLoaded() {
        FabricLoader loader = FabricLoader.getInstance();
        return loader.isModLoaded(SOURCE_MOD_ID) && loader.isModLoaded(TARGET_MOD_ID);
    }

    public static String status() {
        return MOD_ID + ": " + SOURCE_MOD_ID + "=" + modState(SOURCE_MOD_ID)
            + ", " + TARGET_MOD_ID + "=" + modState(TARGET_MOD_ID);
    }

    private static String modState(String modId) {
        return FabricLoader.getInstance().isModLoaded(modId) ? "loaded" : "missing";
    }

    /** Called by the mixin immediately before the integrated/dedicated server shuts down. */
    public static void onServerShutdown() {
        ADAPTER.onServerShutdown();
    }
}
`
}

function adapterSource(packageName: string): string {
  return `package ${packageName};

import net.minecraft.server.MinecraftServer;

/**
 * The seam between the two mods.
 *
 * Keep third-party types out of this interface: the generated project must still
 * compile when one of the peers is not installed, and a bridge that hard-depends
 * on both APIs at class-load time cannot do that.
 */
public interface BridgeAdapter {
    /** Register blocks, items or other content that translates source content into target shapes. */
    default void onRegister() { }

    /** Both mods are loaded and the server is starting; attach event listeners here. */
    void onServerStarting(MinecraftServer server);

    /** Release listeners and flush any buffered state. */
    default void onServerShutdown() { }
}
`
}

function exampleAdapterSource(packageName: string): string {
  return `package ${packageName};

import net.minecraft.server.MinecraftServer;

/**
 * Generated starting point. Replace the TODOs with calls into the two mods, but
 * keep the guards: a missing peer must leave the bridge idle rather than crash.
 */
public final class ExampleBridgeAdapter implements BridgeAdapter {
    @Override
    public void onRegister() {
        // TODO(registry): map the source mod's registry entries into the target mod's expected form.
        BridgeMod.LOGGER.info("[{}] registry adapter ready", BridgeMod.MOD_ID);
    }

    @Override
    public void onServerStarting(MinecraftServer server) {
        // TODO(events): subscribe to the source mod's events and forward them to the target mod.
        BridgeMod.LOGGER.info("[{}] event adapter attached", BridgeMod.MOD_ID);
    }
}
`
}

function mixinSource(packageName: string): string {
  return `package ${packageName}.mixin;

import ${packageName}.BridgeMod;
import net.minecraft.server.MinecraftServer;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/**
 * The scaffold's mixin wiring proof. Keep it, remove it, or add injectors that
 * adapt calls the two mods cannot reach through public events. The target method
 * is looked up at runtime, so javac cannot validate the name: change it together
 * with the Minecraft version.
 */
@Mixin(MinecraftServer.class)
public abstract class MinecraftServerMixin {
    @Inject(method = "shutdown", at = @At("HEAD"))
    private void modcrafting$beforeShutdown(CallbackInfo info) {
        BridgeMod.onServerShutdown();
    }
}
`
}

function readme(input: {
  modId: string
  modName: string
  sourceModId: string
  sourceModName: string
  targetModId: string
  targetModName: string
}): string {
  return `# ${input.modName}

Generated by ModCrafting as a Fabric bridge between **${input.sourceModName}** (\`${input.sourceModId}\`) and **${input.targetModName}** (\`${input.targetModId}\`).

## What is wired

- Entrypoint \`BridgeMod\` registers the adapter's content hook and listens for server start.
- \`BridgeAdapter\` is the seam: keep third-party types out of it so the bridge still compiles and starts when one peer is absent.
- \`ExampleBridgeAdapter\` contains the two TODO regions:
  1. \`onRegister()\` — translate source registry content into the target mod's expected shape.
  2. \`onServerStarting(MinecraftServer)\` — subscribe to source events and forward them to the target.
- \`MinecraftServerMixin\` demonstrates mixin wiring and calls \`BridgeMod.onServerShutdown()\`; it does not touch either mod's jar.
- \`/${input.modId}-status\` reports whether both peers are loaded.

## Verify

1. Build: \`./gradlew build\` (or \`gradlew.bat build\` on Windows). The generated project compiles before the TODOs are filled in.
2. Install the bridge together with both peers; run \`/${input.modId}-status\` in game.
3. Fill one TODO at a time and keep the bridge loadable with a peer missing.

The scaffold never pulls the peers apart or rewrites their jars. If a peer's code has to change, use the pack transform pipeline and its licence gates instead.
`
}

export async function bridgeScaffold(request: BridgeScaffoldRequest): Promise<Record<string, unknown>> {
  const workspace = loadPackWorkspace(request.workspacePath)
  const { loader, minecraft } = parseTargetId(workspace.manifest.targetId)
  if (loader !== 'fabric') {
    fail('BRIDGE_FABRIC_ONLY', `整合包目标是 ${workspace.manifest.targetId}。整合包导出支持 Fabric/NeoForge/Forge，但 v1 的桥接工程只生成 Fabric 源码；请把桥接作为独立 Fabric 工程，或把目标改为 Fabric。`)
  }

  let target
  try {
    target = resolveTarget(loader, minecraft)
  } catch (cause) {
    fail('BRIDGE_TARGET_UNSUPPORTED', `无法解析 ${workspace.manifest.targetId}：${(cause as Error).message}`)
  }

  const projectPath = path.resolve(request.projectPath)
  if (isInside(path.join(workspace.path, 'mods'), projectPath)) {
    fail('BRIDGE_PATH_FORBIDDEN', `桥接工程不能写进整合包的 mods/ 目录（${projectPath}）；那里是已安装的第三方 jar，生成源码会污染实例。请使用 bridges/ 或仓库内其他目录。`)
  }
  ensureEmpty(projectPath)

  const packageName = javaPackageFor(request.modId)
  await materializeProject({ projectPath, modId: request.modId, modName: request.modName, target })

  // `materializeProject` groups by modId; a Java package is the better Gradle group
  // here, and it keeps the generated coordinate valid if the modId has a dash.
  const buildFile = path.join(projectPath, 'build.gradle')
  writeFileSync(buildFile, readFileSync(buildFile, 'utf8').replace(/^group = '.*'$/m, `group = '${packageName}'`), 'utf8')

  const javaRoot = path.join(projectPath, 'src', 'main', 'java', ...packageName.split('.'))
  mkdirSync(path.join(javaRoot, 'mixin'), { recursive: true })
  const sourceFiles: Record<string, string> = {
    [`src/main/java/${packageName.split('.').join('/')}/BridgeMod.java`]: mainSource({
      packageName,
      modId: request.modId,
      sourceModId: request.sourceModId,
      targetModId: request.targetModId
    }),
    [`src/main/java/${packageName.split('.').join('/')}/BridgeAdapter.java`]: adapterSource(packageName),
    [`src/main/java/${packageName.split('.').join('/')}/ExampleBridgeAdapter.java`]: exampleAdapterSource(packageName),
    [`src/main/java/${packageName.split('.').join('/')}/mixin/MinecraftServerMixin.java`]: mixinSource(packageName)
  }
  for (const [relative, contents] of Object.entries(sourceFiles)) {
    const destination = path.join(projectPath, ...relative.split('/'))
    mkdirSync(path.dirname(destination), { recursive: true })
    writeFileSync(destination, contents, 'utf8')
  }

  const mixinConfig = 'bridge.mixins.json'
  writeFileSync(path.join(projectPath, 'src', 'main', 'resources', mixinConfig), `${JSON.stringify({
    required: true,
    package: `${packageName}.mixin`,
    compatibilityLevel: `JAVA_${target.release.javaTarget}`,
    mixins: ['MinecraftServerMixin'],
    injectors: { defaultRequire: 1 }
  }, null, 2)}\n`, 'utf8')

  const metadataFile = path.join(projectPath, 'src', 'main', 'resources', 'fabric.mod.json')
  const metadata = JSON.parse(readFileSync(metadataFile, 'utf8')) as Record<string, unknown>
  const entrypoint = `${packageName}.BridgeMod`
  metadata.description = `Bridge between ${request.sourceModName ?? request.sourceModId} and ${request.targetModName ?? request.targetModId}.`
  metadata.entrypoints = { ...(metadata.entrypoints as Record<string, unknown> | undefined), main: [entrypoint] }
  metadata.mixins = [{ config: mixinConfig, environment: '*' }]
  metadata.recommends = { [request.sourceModId]: '*', [request.targetModId]: '*' }
  writeFileSync(metadataFile, `${JSON.stringify(metadata, null, 2)}\n`, 'utf8')

  writeFileSync(path.join(projectPath, 'BRIDGE.md'), readme({
    modId: request.modId,
    modName: request.modName,
    sourceModId: request.sourceModId,
    sourceModName: request.sourceModName ?? request.sourceModId,
    targetModId: request.targetModId,
    targetModName: request.targetModName ?? request.targetModId
  }), 'utf8')

  const files = Object.keys(sourceFiles).concat([
    'BRIDGE.md',
    'build.gradle',
    'src/main/resources/bridge.mixins.json',
    'src/main/resources/fabric.mod.json',
    'settings.gradle',
    'gradle.properties',
    '.gitignore'
  ]).sort()

  return {
    ok: true,
    projectPath,
    modId: request.modId,
    modName: request.modName,
    packageName,
    entrypoint,
    mixinConfig,
    targetId: workspace.manifest.targetId,
    loaderVersion: target.release.loaderVersion,
    sourceModId: request.sourceModId,
    targetModId: request.targetModId,
    files,
    notes: [
      '桥接工程只写入自己的目录，不读取或修改两个模组的 jar。',
      '先保持两个 peer 都可缺失：ADAPTER 是唯一需要补完的地方。',
      `构建后在游戏中用 /${request.modId}-status 检查两个模组是否都被加载。`
    ]
  }
}
