/**
 * L2: a companion mixin mod.
 *
 * The companion is a separate project that depends on the source mod and injects
 * against class names supplied as strings. Using `@Mixin(targets = "...")` means
 * the project compiles without the source jar on the classpath, so generating it
 * never requires copying or unpacking third-party bytes into the build.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { materializeProject } from '../../node.ts'
import type { ResolvedTarget } from '../../version/targets.ts'
import { javaPackageFor } from '../java-package.ts'

export interface CompanionTarget {
  className: string
  method?: string
  at?: 'HEAD' | 'TAIL' | 'RETURN'
}

function fail(code: string, message: string): never {
  throw Object.assign(new Error(message), { code })
}

function isInside(parent: string, child: string): boolean {
  const relative = path.relative(path.resolve(parent), path.resolve(child))
  return relative === '' || (!relative.startsWith('..') && !path.isAbsolute(relative))
}

function javaString(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r/g, '\\r').replace(/\n/g, '\\n')
}

function companionModSource(packageName: string, modId: string, sourceModId: string): string {
  return `package ${packageName};

import net.fabricmc.api.ModInitializer;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/** Generated by ModCrafting as an L2 companion for ${sourceModId}. */
public final class CompanionMod implements ModInitializer {
    public static final String MOD_ID = "${javaString(modId)}";
    public static final Logger LOGGER = LoggerFactory.getLogger(MOD_ID);

    @Override
    public void onInitialize() {
        LOGGER.info("[{}] companion loaded; waiting for ${sourceModId}", MOD_ID);
    }
}
`
}

function hooksSource(packageName: string, modId: string): string {
  return `package ${packageName};

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Generated seam for the companion's behaviour. Replace the log with the call the
 * source mod cannot make itself, but keep this class free of compile-time imports
 * from the source mod: the project must keep compiling when that mod changes.
 */
public final class CompanionHooks {
    private static final Logger LOGGER = LoggerFactory.getLogger("${javaString(modId)}");

    private CompanionHooks() { }

    public static void onTarget(String targetClass, String method) {
        // TODO: call into the API that needs adapting.
        LOGGER.info("[{}] hook {}#{}", "${javaString(modId)}", targetClass, method);
    }
}
`
}

function mixinSource(input: { packageName: string; className: string; method?: string; at?: string; index: number }): string {
  const name = `TargetMixin${input.index}`
  if (!input.method) {
    return `package ${input.packageName}.mixin;

import org.spongepowered.asm.mixin.Mixin;

/**
 * TODO: add @Inject methods for ${input.className}. The empty mixin is valid and
 * proves the wiring; it deliberately changes nothing yet.
 */
@Mixin(targets = "${javaString(input.className)}")
public abstract class ${name} {
}
`
  }
  return `package ${input.packageName}.mixin;

import ${input.packageName}.CompanionHooks;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/** Generated L2 hook for ${input.className}#${input.method}. */
@Mixin(targets = "${javaString(input.className)}")
public abstract class ${name} {
    @Inject(method = "${javaString(input.method)}", at = @At("${input.at ?? 'HEAD'}"))
    private void modcrafting$hook(CallbackInfo info) {
        CompanionHooks.onTarget("${javaString(input.className)}", "${javaString(input.method)}");
    }
}
`
}

export async function scaffoldCompanion(input: {
  workspacePath: string
  projectPath: string
  target: ResolvedTarget
  entryId: string
  sourceModId: string
  modId: string
  modName: string
  targets: readonly CompanionTarget[]
  transformId: string
  generatedAt: string
  decision: { allowed: boolean; exportable: boolean; reasons: string[]; message: string; code?: string }
}): Promise<{ files: string[] }> {
  const projectPath = path.resolve(input.projectPath)
  if (isInside(path.join(input.workspacePath, 'mods'), projectPath) || isInside(path.join(input.workspacePath, 'transforms'), projectPath)) {
    fail('TRANSFORM_PATH_FORBIDDEN', `伴生工程不能写进整合包的 mods/ 或 transforms/（${projectPath}）。请换一个目录，例如 <整合包>/companions/<modId>。`)
  }
  if (existsSync(projectPath) && (!statSync(projectPath).isDirectory() || readdirSync(projectPath).length > 0)) {
    fail('TRANSFORM_PATH_NOT_EMPTY', `${projectPath} 已存在且不是空目录。伴生工程只写入新目录；请换一个路径或先手动清空。`)
  }

  await materializeProject({ projectPath, modId: input.modId, modName: input.modName, target: input.target })
  const packageName = javaPackageFor(input.modId)
  const packagePath = packageName.split('.').join('/')
  const buildFile = path.join(projectPath, 'build.gradle')
  writeFileSync(buildFile, readFileSync(buildFile, 'utf8').replace(/^group = '.*'$/m, `group = '${packageName}'`), 'utf8')

  const mixinClasses = input.targets.map((target, index) => ({ name: `TargetMixin${index + 1}`, target }))
  const files: string[] = []
  const write = (relative: string, contents: string) => {
    const destination = path.join(projectPath, ...relative.split('/'))
    mkdirSync(path.dirname(destination), { recursive: true })
    writeFileSync(destination, contents, 'utf8')
    files.push(relative)
  }

  write(`src/main/java/${packagePath}/CompanionMod.java`, companionModSource(packageName, input.modId, input.sourceModId))
  write(`src/main/java/${packagePath}/CompanionHooks.java`, hooksSource(packageName, input.modId))
  for (const [index, mixin] of mixinClasses.entries()) {
    write(
      `src/main/java/${packagePath}/mixin/${mixin.name}.java`,
      mixinSource({
        packageName,
        className: mixin.target.className,
        ...(mixin.target.method ? { method: mixin.target.method } : {}),
        ...(mixin.target.at ? { at: mixin.target.at } : {}),
        index: index + 1
      })
    )
  }

  const mixinConfig = `${input.modId}.mixins.json`
  write(`src/main/resources/${mixinConfig}`, `${JSON.stringify({
    required: true,
    package: `${packageName}.mixin`,
    compatibilityLevel: `JAVA_${input.target.release.javaTarget}`,
    mixins: mixinClasses.map((mixin) => mixin.name),
    injectors: { defaultRequire: 1 }
  }, null, 2)}\n`)

  const metadataFile = path.join(projectPath, 'src', 'main', 'resources', 'fabric.mod.json')
  const metadata = JSON.parse(readFileSync(metadataFile, 'utf8')) as Record<string, unknown>
  metadata.description = `L2 companion for ${input.sourceModId} (generated by ModCrafting).`
  metadata.entrypoints = { ...(metadata.entrypoints as Record<string, unknown> | undefined), main: [`${packageName}.CompanionMod`] }
  metadata.mixins = [{ config: mixinConfig, environment: '*' }]
  metadata.depends = { ...(metadata.depends as Record<string, string>), [input.sourceModId]: '*' }
  metadata.recommends = { }
  writeFileSync(metadataFile, `${JSON.stringify(metadata, null, 2)}\n`, 'utf8')

  const marker = {
    schemaVersion: 1,
    level: 'L2',
    transformId: input.transformId,
    entryId: input.entryId,
    sourceModId: input.sourceModId,
    createdAt: input.generatedAt
  }
  writeFileSync(path.join(projectPath, '.modcrafting-transform.json'), `${JSON.stringify(marker, null, 2)}\n`, 'utf8')
  files.push('.modcrafting-transform.json')

  writeFileSync(path.join(projectPath, 'TRANSFORM.md'), `# ${input.modName} (L2 companion)

Generated by ModCrafting as an L2 companion for \`${input.sourceModId}\`.

- The source jar was not modified; it is not even on the compile classpath.
- Mixins use string targets: \`${input.targets.map((target) => target.className).join('`, `')}\`.
- Fill \`CompanionHooks.onTarget\` with the adaptation, then build like any Fabric project.

Licence decision: ${input.decision.message}
${input.decision.reasons.map((reason) => `- ${reason}`).join('\n')}
`, 'utf8')
  files.push('TRANSFORM.md')

  files.push('build.gradle', 'settings.gradle', 'gradle.properties', 'src/main/resources/fabric.mod.json')
  return { files: [...new Set(files)].sort() }
}
