/**
 * The single source of truth for resource paths and resource JSON dialects.
 *
 * Everything that writes or reads a resource file must come through here.
 * `version/resources-profile.ts` is a re-export shell for older imports; no
 * second implementation is allowed.
 *
 * Two axes live here on purpose:
 *  - paths: where a file goes (`recipe` vs `recipes`, `loot_table/blocks`, ...)
 *  - dialect: what the JSON looks like (ingredient shape, result shape, blockstate wrapper)
 *
 * Both change only with Minecraft, never with the loader, so `loaders/*` must not
 * touch them.
 */
import { ERA } from '../version/eras.ts'
import type { VersionRegistry } from '../version/registry.ts'

const ROOT = 'src/main/resources'

export type RecipeDir = 'recipe' | 'recipes'
export type LootTableDir = 'loot_table' | 'loot_tables'
export type ItemTagDir = 'tags/item' | 'tags/items'
export type BlockTagDir = 'tags/block' | 'tags/blocks'
export type AdvancementDir = 'advancement' | 'advancements'
export type ItemModelDefinitionMode = 'assets-items' | 'none'
export type BlockstateDialect = 'variants-v1' | 'variants-v2'
export type RecipeIngredientDialect = 'string' | 'object'
export type RecipeResultDialect = 'id-object' | 'item-object'

/**
 * Resource *shapes* whose exact field layout is not yet proven against a real
 * client jar. Shape evidence is deliberately separate from `ERA`: a shape is not
 * an era, and several eras legitimately share one boundary version.
 */
export type ResourceShape = 'blockstateV2' | 'itemModelDefinition' | 'legacyStonecuttingResult'

export const RESOURCE_SHAPE_EVIDENCE: Record<ResourceShape, { confirmed: boolean; boundary: keyof typeof ERA; note: string }> = {
  blockstateV2: {
    confirmed: false,
    boundary: 'blockstateV2',
    note: '1.21.5+ 的 blockstate / 模型包装字段尚未用真实 client jar 证实；当前沿用 variants-v1 结构'
  },
  itemModelDefinition: {
    confirmed: true,
    boundary: 'itemModelDefinition',
    note: '1.21.4 的 assets/<ns>/items/<name>.json 已在工程与 vanilla 资源中验证'
  },
  legacyStonecuttingResult: {
    confirmed: false,
    boundary: 'resultIdField',
    note: '1.20.x 的 stonecutting result 是否为字符串尚未证实；当前按字符串 + count 输出'
  }
}

export interface ResourceDialect {
  readonly recipeDir: RecipeDir
  readonly lootTableDir: LootTableDir
  readonly tagsDir: ItemTagDir
  readonly advancementDir: AdvancementDir
  readonly itemModelDefinition: ItemModelDefinitionMode
  readonly blockstate: BlockstateDialect
  readonly recipeIngredient: RecipeIngredientDialect
  readonly recipeResult: RecipeResultDialect
}

export interface ResourceLayout extends ResourceDialect {
  readonly minecraft: string
  blockstatePath(namespace: string, name: string): string
  blockModelPath(namespace: string, name: string): string
  itemModelPath(namespace: string, name: string): string
  /** Undefined when the target does not use item model definitions. */
  itemModelDefinitionPath(namespace: string, name: string): string | undefined
  /** `relative` keeps its own category segments, e.g. `item/ruby` or `entity/pig/pig`. */
  texturePath(namespace: string, relative: string): string
  langPath(namespace: string, locale: string): string
  recipePath(namespace: string, name: string): string
  blockLootTablePath(namespace: string, name: string): string
  tagPath(namespace: string, kind: 'item' | 'block', name: string): string
  advancementPath(namespace: string, name: string): string
  /** Target directory first, legacy second. Readers scan both, writers use [0]. */
  recipeDirs(): readonly [RecipeDir, RecipeDir]
  parseRecipePath(file: string): { namespace: string; name: string; dir: RecipeDir; inTargetDialect: boolean } | undefined
  tagDirFor(kind: 'item' | 'block'): ItemTagDir | BlockTagDir
}

export function resourceDialect(layout: ResourceLayout): ResourceDialect {
  return {
    recipeDir: layout.recipeDir,
    lootTableDir: layout.lootTableDir,
    tagsDir: layout.tagsDir,
    advancementDir: layout.advancementDir,
    itemModelDefinition: layout.itemModelDefinition,
    blockstate: layout.blockstate,
    recipeIngredient: layout.recipeIngredient,
    recipeResult: layout.recipeResult
  }
}

/**
 * Equality key for "did the target change in a way that changes generated bytes".
 *
 * Unconfirmed dimensions are excluded on purpose: they do not alter emitted
 * bytes yet, so including them would force a migration that rewrites nothing.
 * The moment a shape becomes confirmed and implemented, this signature changes
 * and migrations start being requested — which is exactly the intent.
 */
export function dialectSignature(layout: ResourceLayout): string {
  const dialect = resourceDialect(layout)
  const parts: string[] = [dialect.recipeDir, dialect.lootTableDir, dialect.tagsDir, dialect.advancementDir, dialect.itemModelDefinition, dialect.recipeIngredient, dialect.recipeResult]
  if (RESOURCE_SHAPE_EVIDENCE.blockstateV2.confirmed) parts.push(dialect.blockstate)
  return parts.join('|')
}

export function unconfirmedShapes(layout: ResourceLayout): string[] {
  const shapes: ResourceShape[] = []
  if (layout.blockstate === 'variants-v2') shapes.push('blockstateV2')
  if (layout.itemModelDefinition === 'assets-items') shapes.push('itemModelDefinition')
  if (layout.recipeResult === 'item-object') shapes.push('legacyStonecuttingResult')
  return shapes.filter((shape) => !RESOURCE_SHAPE_EVIDENCE[shape].confirmed).map((shape) => RESOURCE_SHAPE_EVIDENCE[shape].note)
}

const RECIPE_PATH_RE = /(?:^|\/)src\/main\/resources\/data\/([a-z0-9_.-]+)\/(recipe|recipes)\/([a-z0-9/._-]+)\.json$/

export function deriveResourceLayout(minecraft: string, registry: VersionRegistry): ResourceLayout {
  const singular = registry.atLeast(minecraft, ERA.singularDataDir)
  const modernResult = registry.atLeast(minecraft, ERA.resultIdField)
  const itemDefinitions = registry.atLeast(minecraft, ERA.itemModelDefinition)
  const blockstateV2 = registry.atLeast(minecraft, ERA.blockstateV2)
  const recipeDir: RecipeDir = singular ? 'recipe' : 'recipes'
  const lootTableDir: LootTableDir = singular ? 'loot_table' : 'loot_tables'
  const tagsDir: ItemTagDir = singular ? 'tags/item' : 'tags/items'

  return {
    minecraft,
    recipeDir,
    lootTableDir,
    tagsDir,
    advancementDir: singular ? 'advancement' : 'advancements',
    itemModelDefinition: itemDefinitions ? 'assets-items' : 'none',
    blockstate: blockstateV2 ? 'variants-v2' : 'variants-v1',
    recipeIngredient: registry.atLeast(minecraft, ERA.stringRecipeIngredient) ? 'string' : 'object',
    recipeResult: modernResult ? 'id-object' : 'item-object',
    blockstatePath: (namespace, name) => `${ROOT}/assets/${namespace}/blockstates/${name}.json`,
    blockModelPath: (namespace, name) => `${ROOT}/assets/${namespace}/models/block/${name}.json`,
    itemModelPath: (namespace, name) => `${ROOT}/assets/${namespace}/models/item/${name}.json`,
    itemModelDefinitionPath: (namespace, name) => itemDefinitions ? `${ROOT}/assets/${namespace}/items/${name}.json` : undefined,
    texturePath: (namespace, relative) => `${ROOT}/assets/${namespace}/textures/${relative}.png`,
    langPath: (namespace, locale) => `${ROOT}/assets/${namespace}/lang/${locale}.json`,
    recipePath: (namespace, name) => `${ROOT}/data/${namespace}/${recipeDir}/${name}.json`,
    blockLootTablePath: (namespace, name) => `${ROOT}/data/${namespace}/${lootTableDir}/blocks/${name}.json`,
    tagPath: (namespace, kind, name) => `${ROOT}/data/${namespace}/${kind === 'item' ? tagsDir : `${singular ? 'tags/block' : 'tags/blocks'}`}/${name}.json`,
    advancementPath: (namespace, name) => `${ROOT}/data/${namespace}/${singular ? 'advancement' : 'advancements'}/${name}.json`,
    recipeDirs: () => [recipeDir, recipeDir === 'recipe' ? 'recipes' : 'recipe'],
    parseRecipePath(file) {
      const match = path_normalize(file).match(RECIPE_PATH_RE)
      if (!match) return undefined
      const dir = match[2] as RecipeDir
      return { namespace: match[1], name: match[3], dir, inTargetDialect: dir === recipeDir }
    },
    tagDirFor: (kind) => kind === 'item' ? tagsDir : singular ? 'tags/block' : 'tags/blocks'
  }
}

const path_normalize = (file: string): string => file.replaceAll('\\', '/')
