import test from 'node:test'
import assert from 'node:assert/strict'
import { existsSync, mkdtempSync, mkdirSync, readFileSync } from 'node:fs'
import path from 'node:path'
import { materializeProject, materializeVersions } from '../../packages/modcrafting-core/src/node.ts'
import { resolveTarget } from '../../packages/modcrafting-core/src/version/targets.ts'

const root = () => { mkdirSync('temp', { recursive: true }); return path.join(mkdtempSync(path.resolve('temp/materialize-unit-')), 'project') }
const read = (project: string, file: string) => readFileSync(path.join(project, file), 'utf8')

test('materialize writes the per-target Minecraft, loader, API and mappings', async () => {
  const project = await materializeProject({ projectPath: root(), modId: 'probe_mod', modName: 'Probe', target: resolveTarget('fabric', '1.20.1') })
  const properties = read(project.path, 'gradle.properties')
  assert.match(properties, /^minecraft_version=1\.20\.1$/m)
  assert.match(properties, /^yarn_mappings=1\.20\.1\+build\.10$/m)
  assert.match(properties, /^loader_version=0\.20\.1$/m)
  assert.match(properties, /^fabric_version=0\.92\.9\+1\.20\.1$/m)
  assert.match(read(project.path, 'build.gradle'), /com\.mojang:minecraft:1\.20\.1/)
  assert.match(read(project.path, 'build.gradle'), /fabric-api:0\.92\.9\+1\.20\.1/)
  const metadata = JSON.parse(read(project.path, 'src/main/resources/fabric.mod.json'))
  assert.equal(metadata.depends.minecraft, '~1.20.1')
  assert.equal(metadata.depends.java, '>=17', 'the Java requirement is a target property')
})

test('materialize keeps the shipped build toolchain for every target', async () => {
  // Probed 2026-11-16: maven's newest Loom needs Gradle 9.8, which we do not ship.
  for (const [minecraft, loom] of [['1.20.1', '1.17.12'], ['1.21.4', '1.17.12']] as const) {
    const versions = materializeVersions(resolveTarget('fabric', minecraft))
    assert.equal(versions.loom, loom, `${minecraft} must reuse the shipped Loom`)
    assert.equal(versions.gradle, '9.5.0')
  }
})

test('materialize keeps the pinned 1.21.4 tuple byte-stable', async () => {
  const versions = materializeVersions(resolveTarget('fabric', '1.21.4'))
  assert.deepEqual(versions, { minecraft: '1.21.4', loader: '0.16.10', api: '0.116.0+1.21.4', mappings: '1.21.4+build.1', mappingKind: 'yarn', loom: '1.17.12', gradle: '9.5.0', javaMajor: 21 })
  const project = await materializeProject({ projectPath: root(), modId: 'pinned_mod', modName: 'Pinned', target: resolveTarget('fabric', '1.21.4') })
  assert.equal(read(project.path, 'gradle.properties'), 'minecraft_version=1.21.4\nyarn_mappings=1.21.4+build.1\nloader_version=0.16.10\nfabric_version=0.116.0+1.21.4\n')
  assert.equal(existsSync(path.join(project.path, 'src/main/java')), false, 'no Java is generated by materialize')
})

test('materialize builds the neoforge and forge structures', async () => {
  const wrapper = { batch: '@echo off\r\n', properties: 'distributionUrl=gradle-9.5.0-bin.zip\n', jarBase64: Buffer.from('jar').toString('base64') }
  const project = await materializeProject({ projectPath: root(), modId: 'neo_mod', modName: 'Neo Probe', target: resolveTarget('neoforge', '1.21.4'), wrapper })
  assert.equal(project.loader, 'neoforge', 'inspection recognizes the platform metadata')
  assert.equal(project.valid, true, project.errors.join('; '))
  const metadata = read(project.path, 'src/main/resources/META-INF/neoforge.mods.toml')
  assert.match(metadata, /modId = "neo_mod"/)
  assert.match(metadata, /versionRange = "\[1\.21\.4,\)"/)
  assert.match(read(project.path, 'build.gradle'), /id 'net\.neoforged\.moddev'/)
  assert.match(read(project.path, 'build.gradle'), /neoForge \{ version = '21\.4\.161' \}/)
  assert.match(read(project.path, 'gradle.properties'), /^minecraft_version=1\.21\.4$/m)
  assert.match(read(project.path, 'src/main/java/modcrafting/generated/neo_mod/Main.java'), /@Mod\(Main\.MOD_ID\)/)
  assert.equal(existsSync(path.join(project.path, 'src/main/resources/fabric.mod.json')), false, 'no Fabric metadata leaks into a NeoForge project')

  const forge = await materializeProject({ projectPath: root(), modId: 'forge_mod', modName: 'Forge Probe', target: resolveTarget('forge', '1.20.1'), wrapper })
  assert.equal(forge.loader, 'forge', 'Forge 有自己的元数据文件（mods.toml）')
  assert.equal(forge.valid, true, forge.errors.join('; '))
  const forgeMetadata = read(forge.path, 'src/main/resources/META-INF/mods.toml')
  assert.match(forgeMetadata, /modId = "forge_mod"/)
  assert.match(forgeMetadata, /mandatory = true/, 'Forge 的依赖字段是 mandatory，不是 type')
  const forgeBuild = read(forge.path, 'build.gradle')
  assert.match(forgeBuild, /id 'net\.minecraftforge\.gradle'/)
  assert.match(forgeBuild, /minecraft 'net\.minecraftforge:forge:1\.20\.1-47\.4\.28'/)
  assert.match(read(forge.path, 'settings.gradle'), /maven\.minecraftforge\.net/, 'ForgeGradle 只在 Forge 自己的 maven 上')
  assert.match(read(forge.path, 'src/main/java/modcrafting/generated/forge_mod/Main.java'), /FMLJavaModLoadingContext/)
})

test('the year-based line reports the Java version it actually needs', () => {
  assert.equal(materializeVersions(resolveTarget('fabric', '26.3')).javaMajor, 25)
  assert.equal(materializeVersions(resolveTarget('fabric', '1.21.11')).javaMajor, 21)
})
